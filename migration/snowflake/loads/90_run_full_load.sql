-- Unit 3 (loads): one Talend-equivalent run (initial load / cutover / recovery), in the Talend run order.
-- Run after the deploy (ddl/ -> loads/00..60 -> procedures/) and after PUTting the files (01_stage.sql header).
-- Expected result on the repo's source files (migration/baseline/): DimBranch 5, DimAccount 21,
-- DimCustomer 20, FactTransaction 22 rows; 7 reject rows per full run (EXCEL 6, 7 and CSV 14, 15 as
-- DUPLICATE_LOWER_PRECEDENCE; CSV 23, 24, 25 as ORPHAN_ACCOUNT).

USE DATABASE BANKING_DWH;

CALL OPS.SP_COPY_RAW(TRUE);
CALL OPS.SP_LOAD_DIMBRANCH();
CALL OPS.SP_LOAD_DIMACCOUNT();
CALL OPS.SP_LOAD_DIMCUSTOMER();
CALL OPS.SP_LOAD_FACTTRANSACTION();

SELECT
    'DIMBRANCH' AS TABLE_NAME,
    COUNT(*) AS ROW_COUNT
FROM DWH.DIMBRANCH
UNION ALL
SELECT
    'DIMACCOUNT' AS TABLE_NAME,
    COUNT(*) AS ROW_COUNT
FROM DWH.DIMACCOUNT
UNION ALL
SELECT
    'DIMCUSTOMER' AS TABLE_NAME,
    COUNT(*) AS ROW_COUNT
FROM DWH.DIMCUSTOMER
UNION ALL
SELECT
    'FACTTRANSACTION' AS TABLE_NAME,
    COUNT(*) AS ROW_COUNT
FROM DWH.FACTTRANSACTION;

SELECT
    REJECTREASON,
    SOURCESYSTEM,
    COUNT(*) AS REJECTED_ROWS
FROM OPS.FACTTRANSACTION_REJECTS
WHERE REJECTEDAT = (SELECT MAX(R.REJECTEDAT) FROM OPS.FACTTRANSACTION_REJECTS AS R)
GROUP BY REJECTREASON, SOURCESYSTEM
ORDER BY REJECTREASON, SOURCESYSTEM;
