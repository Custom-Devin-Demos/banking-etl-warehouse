-- Unit 3 (loads): RAW landing tables, one per source (PLAN.md §3). Source column names, typed, plus metadata.
-- IF NOT EXISTS: RAW keeps every load (history / replay source); redeploys must not empty it.

USE DATABASE BANKING_DWH;

CREATE TABLE IF NOT EXISTS RAW.STATE (
    STATE_ID INT,
    STATE_NAME VARCHAR(50),
    _SOURCE_FILE VARCHAR,
    _SOURCE_ROW NUMBER,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT SYSDATE()
)
COMMENT = 'Landing: sample.dbo.state extract';

CREATE TABLE IF NOT EXISTS RAW.CITY (
    CITY_ID INT,
    CITY_NAME VARCHAR(50),
    STATE_ID INT,
    _SOURCE_FILE VARCHAR,
    _SOURCE_ROW NUMBER,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT SYSDATE()
)
COMMENT = 'Landing: sample.dbo.city extract';

CREATE TABLE IF NOT EXISTS RAW.CUSTOMER (
    CUSTOMER_ID INT,
    CUSTOMER_NAME VARCHAR(50),
    ADDRESS VARCHAR,
    CITY_ID INT,
    AGE VARCHAR(3),
    GENDER VARCHAR(10),
    EMAIL VARCHAR(50), -- noqa: RF04
    _SOURCE_FILE VARCHAR,
    _SOURCE_ROW NUMBER,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT SYSDATE()
)
COMMENT = 'Landing: sample.dbo.customer extract (age kept as VARCHAR(3) like the source)';

CREATE TABLE IF NOT EXISTS RAW.ACCOUNT (
    ACCOUNT_ID INT,
    CUSTOMER_ID INT,
    ACCOUNT_TYPE VARCHAR(10),
    BALANCE INT,
    DATE_OPENED TIMESTAMP_NTZ(0),
    STATUS VARCHAR(10),
    _SOURCE_FILE VARCHAR,
    _SOURCE_ROW NUMBER,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT SYSDATE()
)
COMMENT = 'Landing: sample.dbo.account extract';

CREATE TABLE IF NOT EXISTS RAW.BRANCH (
    BRANCH_ID INT,
    BRANCH_NAME VARCHAR(50),
    BRANCH_LOCATION VARCHAR(50),
    _SOURCE_FILE VARCHAR,
    _SOURCE_ROW NUMBER,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT SYSDATE()
)
COMMENT = 'Landing: sample.dbo.branch extract';

CREATE TABLE IF NOT EXISTS RAW.TRANSACTION_DB (
    TRANSACTION_ID INT,
    ACCOUNT_ID INT,
    TRANSACTION_DATE TIMESTAMP_NTZ(0),
    AMOUNT INT,
    TRANSACTION_TYPE VARCHAR(50),
    BRANCH_ID INT,
    _SOURCE_FILE VARCHAR,
    _SOURCE_ROW NUMBER,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT SYSDATE()
)
COMMENT = 'Landing: sample.dbo.transaction_db extract (fact source rank 1)';

CREATE TABLE IF NOT EXISTS RAW.TRANSACTION_EXCEL (
    TRANSACTION_ID INT,
    ACCOUNT_ID INT,
    TRANSACTION_DATE TIMESTAMP_NTZ(0),
    AMOUNT INT,
    TRANSACTION_TYPE VARCHAR(50),
    BRANCH_ID INT,
    _SOURCE_FILE VARCHAR,
    _SOURCE_ROW NUMBER,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT SYSDATE()
)
COMMENT = 'Landing: transaction_excel.xlsx Sheet1 (fact source rank 2)';

CREATE TABLE IF NOT EXISTS RAW.TRANSACTION_CSV (
    TRANSACTION_ID INT,
    ACCOUNT_ID INT,
    TRANSACTION_DATE TIMESTAMP_NTZ(0),
    AMOUNT INT,
    TRANSACTION_TYPE VARCHAR(50),
    BRANCH_ID INT,
    _SOURCE_FILE VARCHAR,
    _SOURCE_ROW NUMBER,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT SYSDATE()
